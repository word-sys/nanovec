#ifndef NANOVEC_VERSION_H
#define NANOVEC_VERSION_H

#define NANOVEC_VERSION_MAJOR 0
#define NANOVEC_VERSION_MINOR 1
#define NANOVEC_VERSION_PATCH 0

#define NANOVEC_STR_HELPER(x) #x
#define NANOVEC_STR(x) NANOVEC_STR_HELPER(x)

#define NANOVEC_VERSION_STRING \
    NANOVEC_STR(NANOVEC_VERSION_MAJOR) "." \
    NANOVEC_STR(NANOVEC_VERSION_MINOR) "." \
    NANOVEC_STR(NANOVEC_VERSION_PATCH)

#define NANOVEC_VERSION_ENCODE(major, minor, patch) \
    (((major) * 1000000) + ((minor) * 1000) + (patch))

#define NANOVEC_VERSION \
    NANOVEC_VERSION_ENCODE( \
        NANOVEC_VERSION_MAJOR, \
        NANOVEC_VERSION_MINOR, \
        NANOVEC_VERSION_PATCH)

#endif /* NANOVEC_VERSION_H */
